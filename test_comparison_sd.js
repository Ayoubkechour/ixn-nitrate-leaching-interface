/* Categorical comparisons must show sample SD while preserving source rows. */
'use strict';
const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
const source=fs.readFileSync('dist/results_explorer.js','utf8');
const start=source.indexOf('function sampleSummary('),end=source.indexOf("$('chartX').onchange",start);
assert(start>=0&&end>start,'comparison chart functions are present');
const elements={chartX:{value:'Irrigation_treatment',selectedOptions:[{text:'Irrigation treatment'}]},chartMetric:{value:'Load_kg_ha',selectedOptions:[{text:'Analyte load · kg/ha'}]},plotChart:{innerHTML:''},chartContext:{textContent:''},downloadXYFigure:{},downloadXYPairs:{}};
const context={state:{},$:id=>elements[id],finiteValue:value=>typeof value==='number'&&Number.isFinite(value),esc:value=>String(value).replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char])),number:(value,digits=2)=>value==null?'—':Number(value).toFixed(digits)};
vm.createContext(context);vm.runInContext(source.slice(start,end),context);
const row=(plot,value,overrides={})=>({Dataset:'Study',Site:'Field',Year:2022,Plot:plot,Irrigation_treatment:'I1',Nitrogen_treatment:'N1',Load_kg_ha:value,Rain_mm:plot,Custom_source:'original row',...overrides});
const chart=(rows,x='Irrigation_treatment')=>{elements.chartX.value=x;elements.chartX.selectedOptions[0].text=x;context.drawXYChart(rows);return elements.plotChart.innerHTML;};
const stats=context.sampleSummary([0,0,9]);
assert.strictEqual(stats.mean,3);assert(Math.abs(stats.sd-Math.sqrt(27))<1e-12,'SD uses n − 1');
assert.strictEqual(context.sampleSummary([4]).sd,null,'one observation has no sample SD');
assert.strictEqual(context.sampleSummary([4,4]).sd,0,'equal replicated observations have zero SD');
let svg=chart([row(1,0),row(2,0),row(3,9),row(4,null)]);
assert(svg.includes('mean 3.00 · n=3 · sample SD 5.20'),'mean/SD/count tooltip');
assert(svg.includes('[-2.20, 8.20]'),'full mean ± SD interval');
assert(svg.includes('>-2.2</text>'),'axis includes negative mean − SD');
assert.strictEqual((svg.match(/class="sd-whisker"/g)||[]).length,1,'one whisker per replicated group');
const whisker=svg.match(/class="sd-whisker"[\s\S]*?<line x1="[^"]+" y1="([^"]+)" x2="[^"]+" y2="([^"]+)"/);
assert(whisker&&Number(whisker[1])>=31.999&&Number(whisker[2])<=266.001,'whisker remains inside expanded axis');
assert(context.state.xyExport.figure.includes('sd-whisker')&&context.state.xyExport.figure.includes('mean ± 1 sample SD'),'export keeps error bars and notation');
assert.strictEqual(context.state.xyExport.sources.length,3,'missing metric row excluded');
assert.strictEqual(context.state.xyExport.sources[0].Custom_source,'original row','source CSV preserves full raw rows');
assert.strictEqual(context.state.xyExport.sources[2].Load_kg_ha,9,'source CSV keeps unaggregated values');
svg=chart([row(1,4),row(2,4),row(3,10,{Irrigation_treatment:'I2'})]);
assert(svg.includes('sample SD 0.00'),'zero SD is represented');
assert(svg.includes('I2 · mean 10.00 · n=1 · SD unavailable'),'singleton group has no fabricated SD');
assert.strictEqual((svg.match(/class="sd-whisker"/g)||[]).length,1);
svg=chart([row(101,2),row(101,8,{Year:2023})],'Plot');
assert.strictEqual((svg.match(/class="sd-whisker"/g)||[]).length,0,'individual plot-year bars do not pool replicates');
assert(svg.includes('Individual plot-years · SD unavailable (n = 1)'));
assert(svg.includes('2022 · plot 101 · value 2.00')&&svg.includes('2023 · plot 101 · value 8.00'),'same plot ID in two years stays two observations');
svg=chart([row(1,2,{Year:2021}),row(2,6,{Year:2021}),row(3,9,{Year:2022})],'Year');
assert(svg.includes('2021 · mean 4.00 · n=2 · sample SD 2.83'),'year bars use sample SD');
svg=chart([row(1,2),row(2,8)],'Rain_mm');
assert.strictEqual((svg.match(/<circle /g)||[]).length,2,'numeric scatter remains individual points');
assert(!svg.includes('sd-whisker')&&!elements.chartContext.textContent.includes('Bars show mean'),'numeric scatter is unchanged');
console.log('Comparison sample SD regression checks passed');
